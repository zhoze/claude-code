#!/usr/bin/env python3
"""aegis-zone-sync — generate systemd zone drop-ins FROM the agent manifests.

The old design shipped a static example drop-in that nothing installed, so
manifests and units could drift apart (and did: a "high" manifest with no
drop-in runs as aegis-lt — with Gate access). Generation removes the drift:
the manifest is the single source of truth, and this script is idempotent.

For every /aegis/config/agents/<name>.toml this writes
/etc/systemd/system/aegis-agent@<name>.service.d/zone.conf with:

  * User/Group for the manifest's zone (aegis-lt / aegis-ht)
  * the zone's working directory and an explicit ReadWritePaths RESET —
    drop-ins APPEND to path lists, so without the reset a high-trust agent
    would inherit write access to the low-trust scratch (an exfiltration
    channel between zones)
  * MemoryMax from limits.memory_gib (limits stop being decorative)
  * an emptied proxy environment for high trust

Run after every manifest change, then `systemctl daemon-reload`.
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, "/aegis/src")
from aegis_core import registry  # noqa: E402

UNIT_DIR = Path("/etc/systemd/system")

HEADER = """\
# GENERATED by aegis-zone-sync from {source} — do not edit by hand.
# Re-run /aegis/bin/aegis-zone-sync after changing the manifest.
"""

LOW = """\
[Service]
User=aegis-lt
Group=aegis-lt
WorkingDirectory=/aegis/scratch/lt
ReadWritePaths=
ReadWritePaths=/aegis/scratch/lt
Environment=AEGIS_TRUST_ZONE=low
MemoryMax={mem}G
"""

HIGH = """\
[Service]
User=aegis-ht
Group=aegis-ht
WorkingDirectory=/aegis/scratch/ht
# Reset, then re-grant: drop-ins APPEND to ReadWritePaths, and inheriting
# the low-trust scratch would hand high trust a write channel into the
# zone that talks to the internet. The vector db is reached over
# 127.0.0.1:6333 only — its files have exactly one writer (aegis-vectordb).
ReadWritePaths=
ReadWritePaths=/aegis/scratch/ht
ReadOnlyPaths=/aegis/knowledge
# No proxy. A high-trust agent has no route out; nftables enforces it and
# the runner refuses to start if this is ever set.
Environment=HTTPS_PROXY=
Environment=HTTP_PROXY=
Environment=AEGIS_TRUST_ZONE=high
MemoryMax={mem}G
"""


def main() -> int:
    agents = registry.load_all()
    if not agents:
        print("no agent manifests found — nothing to sync")
        return 0
    for m in agents.values():
        dropin_dir = UNIT_DIR / f"aegis-agent@{m.name}.service.d"
        dropin_dir.mkdir(parents=True, exist_ok=True)
        body = (HIGH if m.trust_zone == "high" else LOW).format(mem=m.memory_gib)
        path = dropin_dir / "zone.conf"
        content = HEADER.format(source=m.source) + body
        if path.exists() and path.read_text() == content:
            print(f"  unchanged: {path}")
            continue
        path.write_text(content)
        path.chmod(0o644)
        print(f"  wrote: {path}  (zone={m.trust_zone}, mem={m.memory_gib}G)")
    print("run `systemctl daemon-reload` to pick the drop-ins up")
    return 0


if __name__ == "__main__":
    sys.exit(main())
